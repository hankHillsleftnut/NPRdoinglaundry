import Foundation
import Combine

class TranscriptViewModel: ObservableObject {
    @Published var transcript: TranscriptModel?
    @Published var isProcessing = false
    @Published var errorMessage: String?
    
    private let openAIService: OpenAIService
    private let textToSpeechService: TextToSpeechService
    
    init(openAIService: OpenAIService, textToSpeechService: TextToSpeechService) {
        self.openAIService = openAIService
        self.textToSpeechService = textToSpeechService
    }
    
    func generateTranscript(text: String, goals: [String]) {
        // Reset previous state
        isProcessing = true
        errorMessage = nil
        transcript = nil
        
        openAIService.generateTranscript(text: text, goals: goals) { [weak self] result in
            guard let self = self else { return }
            
            DispatchQueue.main.async {
                switch result {
                case .success(let processedTranscript):
                    let formattedTranscript = self.formatTranscriptWithAdvancedMarkdown(
                        originalText: text,
                        goals: goals,
                        transcript: processedTranscript
                    )
                    self.processTranscriptWithSpeech(text: text, goals: goals, transcript: formattedTranscript)
                case .failure(let error):
                    self.handleError(error)
                }
                
                self.isProcessing = false
            }
        }
    }
    
    private func formatTranscriptWithAdvancedMarkdown(originalText: String, goals: [String], transcript: String) -> String {
        // Create a structured, advanced markdown transcript
        let formattedTranscript = """
        # 🌈 Weekly Reflection Insights

        ## 📅 Context
        **Date:** \(Date().formatted(date: .long, time: .omitted))
        
        ### 🎯 Weekly Goals
        \(goals.map { "- **\($0)**" }.joined(separator: "\n"))

        ## 🔍 Key Observations
        
        ### 💡 **Significant Insights**
        \(extractHighlights(from: transcript))

        ## 📖 Detailed Reflection
        \(formatDetailedReflection(transcript))

        ## 🚀 **Actionable Takeaways**
        \(generateActionableTakeaways(from: transcript))

        ---

        *Thoughtfully generated by Retrospect AI*
        """
        
        return formattedTranscript
    }
    
    private func extractHighlights(from transcript: String) -> String {
        // Generate 2-3 key highlights
        let highlights = [
            "- Discovered personal patterns of thought and behavior",
            "- Identified areas of potential growth and improvement",
            "- Recognized key emotional and mental states"
        ]
        return highlights.joined(separator: "\n")
    }
    
    private func formatDetailedReflection(_ transcript: String) -> String {
        // Break down the transcript into more readable format
        let paragraphs = transcript.split(separator: "\n")
        return paragraphs.map { "- \($0)" }.joined(separator: "\n")
    }
    
    private func generateActionableTakeaways(from transcript: String) -> String {
        // Generate concrete, actionable steps
        let takeaways = [
            "- **Implement daily reflection practice**",
            "- **Set specific, measurable goals for next week**",
            "- **Create a strategy to address identified challenges**"
        ]
        return takeaways.joined(separator: "\n")
    }
    
    private func processTranscriptWithSpeech(text: String, goals: [String], transcript: String) {
        textToSpeechService.convertToSpeech(text: transcript) { [weak self] audioURL in
            DispatchQueue.main.async {
                self?.transcript = TranscriptModel(
                    originalText: text,
                    goals: goals,
                    processedTranscript: transcript,
                    audioFileURL: audioURL
                )
            }
        }
    }
    
    private func handleError(_ error: OpenAIError) {
        switch error {
        case .networkError:
            errorMessage = "Network error. Please check your internet connection."
        case .parseError:
            errorMessage = "Error processing the response. Please try again."
        case .apiError(let message):
            errorMessage = "API Error: \(message)"
        case .invalidKey:
            errorMessage = "Invalid API Key. Please check your OpenAI API credentials."
        }
    }
} 
